"""MySQL database connection.

Targets the relational CIM schemas generated by UCAiug CIMTool's
"ANSI-SQL-92" builder (https://cimtool.ucaiug.io). Those schemas quote
identifiers with double quotes ("Terminal", "mRID"), so every session is
switched into MySQL's ANSI_QUOTES mode on connect. Under ANSI_QUOTES,
string literals in ad-hoc queries must use single quotes; backtick-quoted
identifiers keep working.

Configuration comes from the cimgraph env vars CIMG_HOST, CIMG_PORT,
CIMG_USERNAME, CIMG_PASSWORD and CIMG_DATABASE. The database does not
need to exist yet: `create_schema()` creates it.
"""

from __future__ import annotations

import logging

import mysql.connector

from cimgraph.databases import (get_cim_profile, get_database, get_host, get_namespace,
                                get_password, get_port, get_username)
from cimloader.databases import ConnectionInterface, QueryResponse
from cimloader.databases._config_utils import clear_cim_config_cache

_log = logging.getLogger(__name__)


def split_sql_script(script: str) -> list[str]:
    """Split a CIMTool SQL script into individual statements.

    Full-line `--` comments are dropped first: CIMTool emits separator
    lines like `-------`, which MySQL does not treat as comments (it
    requires whitespace after `--`). CIMTool never puts comments or
    semicolons inside a statement line, so splitting on `;` is safe.
    """
    lines = [line for line in script.splitlines() if not line.lstrip().startswith('--')]
    statements = '\n'.join(lines).split(';')
    return [statement.strip() for statement in statements if statement.strip()]


class MySQLConnection(ConnectionInterface):
    def __init__(self) -> None:
        # Clear cached env variables to pick up any configuration changes
        clear_cim_config_cache()

        # Retrieve configuration from environment
        self.cim_profile, self.cim = get_cim_profile()
        self.namespace = get_namespace()
        self.host = get_host()
        self.port = get_port()
        self.username = get_username()
        self.password = get_password()
        self.database = get_database()
        if not self.database:
            raise ValueError("CIMG_DATABASE must be set to the MySQL database name")
        self.connection = None

    def connect(self):
        if not self.connection:
            self.connection = self._open(database=self.database)

    def disconnect(self):
        if self.connection:
            self.connection.close()
        self.connection = None

    def execute(self, query_message: str, params: tuple = ()) -> QueryResponse:
        """Run a SQL statement and return all result rows (empty for DDL/DML).

        `params` fill `%s` placeholders in `query_message`.
        """
        self.connect()
        cursor = self.connection.cursor()
        try:
            cursor.execute(query_message, params)
            return cursor.fetchall() if cursor.with_rows else []
        finally:
            cursor.close()

    def create_schema(self, sql_file: str) -> None:
        """Create the database (if missing) and run a CIMTool SQL schema script.

        Must be called once before uploading. The script's CREATE TABLE
        statements are not idempotent, so call `drop_all()` first to
        rebuild an existing schema.
        """
        with open(sql_file, encoding='utf-8') as f:
            statements = split_sql_script(f.read())

        server = self._open(database=None)
        try:
            cursor = server.cursor()
            cursor.execute(f'CREATE DATABASE IF NOT EXISTS "{self.database}"')
            cursor.execute(f'USE "{self.database}"')
            for statement in statements:
                cursor.execute(statement)
            # Enumeration tables are populated with INSERTs in the script.
            server.commit()
            cursor.close()
        finally:
            server.close()
        _log.info("Created %d-statement schema from %s in MySQL database %s",
                  len(statements), sql_file, self.database)

    def drop_all(self):
        """Drop the whole database, data and schema. Re-run create_schema() after."""
        self.disconnect()
        server = self._open(database=None)
        try:
            cursor = server.cursor()
            cursor.execute(f'DROP DATABASE IF EXISTS "{self.database}"')
            cursor.close()
        finally:
            server.close()

    def table_columns(self) -> dict[str, set[str]]:
        """Return {table name: column names} for every table in the database."""
        rows = self.execute(
            'SELECT TABLE_NAME, COLUMN_NAME FROM information_schema.COLUMNS '
            'WHERE TABLE_SCHEMA = %s',
            (self.database,),
        )
        tables = {}
        for table, column in rows:
            tables.setdefault(table, set()).add(column)
        return tables

    def table_parents(self) -> dict[str, str]:
        """Return {table name: superclass table name} from the schema.

        CIMTool encodes CIM inheritance as a foreign key from each class
        table's "mRID" to its superclass table's "mRID".
        """
        rows = self.execute(
            'SELECT TABLE_NAME, REFERENCED_TABLE_NAME FROM information_schema.KEY_COLUMN_USAGE '
            "WHERE TABLE_SCHEMA = %s AND COLUMN_NAME = 'mRID' AND REFERENCED_COLUMN_NAME = 'mRID'",
            (self.database,),
        )
        return dict(rows)

    def _open(self, database: str | None):
        """Open a new ANSI_QUOTES session, optionally bound to `database`."""
        connection = mysql.connector.connect(
            host=self.host,
            port=self.port,
            user=self.username,
            password=self.password,
            database=database,
        )
        cursor = connection.cursor()
        cursor.execute("SET SESSION sql_mode = CONCAT(@@SESSION.sql_mode, ',ANSI_QUOTES')")
        cursor.close()
        return connection
