"""MySQL uploader for CIM data.

Loads CIM objects into a relational schema generated by UCAiug CIMTool.
The schema must be created first with `create_schema(sql_file)`.

CIMTool maps the CIM class hierarchy to one table per class (class-table
inheritance): a Terminal is stored as one row each in "IdentifiedObject",
"ACDCTerminal" and "Terminal", all keyed by the same "mRID". Each table
only holds the attributes and single-valued associations declared on that
class. This uploader follows the schema's own inheritance chain (not the
cimgraph profile's, which may come from a different CIM version) and
writes a row to every table on it, filling the columns the schema
declares. Objects whose class has no table, and attributes with no
column, are not part of the profile and are skipped.
"""

from __future__ import annotations

import logging
import os
import tempfile
from collections import defaultdict
from enum import Enum
from pathlib import Path

import mysql.connector
import requests

from cimgraph.data_profile.identity import Identity
from cimgraph.data_profile.units import CIMUnit
from cimgraph.databases import JSONLDFile, XMLFile
from cimloader._formats import content_type_from_filename
from cimloader.databases import MySQLConnection

_log = logging.getLogger(__name__)

# cimgraph file parsers used to turn an RDF file into a graph dict.
_PARSERS = {
    'application/rdf+xml': XMLFile,
    'application/ld+json': JSONLDFile,
}


class MySQLUploader(MySQLConnection):
    def upload_from_file(self, filepath: str, filename: str) -> None:
        """Parse an RDF/XML or JSON-LD file with cimgraph and upload it to MySQL."""
        parser = _parser_for(filename)
        path = Path(filepath) / filename
        if not path.is_file():
            raise FileNotFoundError(path)
        graph = parser(str(path)).create_new_graph(None)
        # cimgraph's parsers log and return an empty graph on parse errors.
        if not graph:
            raise ValueError(f"No CIM objects could be parsed from {path}")
        _log.info("Uploading %s to MySQL database %s", filename, self.database)
        self.upload_from_graphmodel(graph)

    def upload_from_url(self, url: str) -> None:
        """Download an RDF/XML or JSON-LD file and upload it to MySQL."""
        filename = os.path.basename(url.split('?', 1)[0].split('#', 1)[0])
        _parser_for(filename)  # fail on unsupported formats before downloading
        _log.info("Fetching %s for upload to MySQL", url)
        resp = requests.get(url)
        resp.raise_for_status()
        with tempfile.TemporaryDirectory(prefix="cimloader-") as tmp_dir:
            (Path(tmp_dir) / filename).write_bytes(resp.content)
            self.upload_from_file(tmp_dir, filename)

    def upload_from_graphmodel(self, graph_dict: dict) -> None:
        """Upload a CIMantic Graphs graph dict to MySQL.

        Accepts the ``graph`` of any GraphModel subclass (FeederModel,
        BusBranchModel, NodeBreakerModel) -- only the objects matter.

        Rows are upserted (INSERT ... ON DUPLICATE KEY UPDATE), so
        re-uploading an object, or uploading a second profile file for the
        same objects, merges into the existing rows. Foreign key checks are
        disabled for the load, as mysqldump does: CIMTool schemas contain
        FK cycles, and references may point at objects in other files.
        """
        tables = self.table_columns()
        parents = self.table_parents()
        if not tables:
            raise RuntimeError(
                f"MySQL database {self.database!r} has no tables. "
                "Call create_schema(sql_file) before uploading."
            )

        batches = defaultdict(list)
        skipped_classes = set()
        object_count = 0
        for cim_class, objects in graph_dict.items():
            if cim_class.__name__ not in tables:
                skipped_classes.add(cim_class.__name__)
                continue
            for obj in objects.values():
                for table, row in _table_rows(obj, tables, parents):
                    columns = tuple(sorted(row))
                    batches[(table, columns)].append(tuple(row[c] for c in columns))
                object_count += 1
        if skipped_classes:
            _log.warning("Skipped classes not in the SQL schema: %s",
                         ', '.join(sorted(skipped_classes)))

        self.connect()
        cursor = self.connection.cursor()
        cursor.execute('SET FOREIGN_KEY_CHECKS = 0')
        try:
            for (table, columns), rows in batches.items():
                cursor.executemany(_upsert_statement(table, columns), rows)
            self.connection.commit()
        except mysql.connector.Error:
            self.connection.rollback()
            raise
        finally:
            cursor.execute('SET FOREIGN_KEY_CHECKS = 1')
            cursor.close()
        _log.info("Uploaded %d objects to MySQL database %s", object_count, self.database)


def _parser_for(filename: str):
    content_type = content_type_from_filename(filename)
    if content_type not in _PARSERS:
        raise ValueError(
            f"MySQLUploader can only parse RDF/XML and JSON-LD files, got {filename!r}"
        )
    return _PARSERS[content_type]


def _table_rows(obj: Identity, tables: dict[str, set[str]],
                parents: dict[str, str]) -> list[tuple[str, dict]]:
    """Return one (table, {column: value}) row per table in obj's schema class hierarchy."""
    rows = []
    table = type(obj).__name__
    while table is not None:
        row = {'mRID': obj.uri()}
        for column in tables[table] - {'mRID'}:
            value = getattr(obj, column, None)
            if value is not None:
                row[column] = _sql_value(value, table, column)
        rows.append((table, row))
        table = parents.get(table)
    return rows


def _sql_value(value, table: str, column: str):
    """Convert a cimgraph attribute value to the value stored in its SQL column."""
    if isinstance(value, Identity):
        # Associations are FK columns holding the referenced object's mRID.
        return value.uri()
    if isinstance(value, Enum):
        # Enumerations are FKs to lookup tables keyed by the literal name.
        return value.value
    if isinstance(value, bool):
        # CIMTool stores booleans as INTEGER CHECK (col IN (0, 1)).
        return int(value)
    if isinstance(value, CIMUnit):
        # CIMUnit values are held in SI base units, as in CIM XML.
        return float(value)
    if isinstance(value, list):
        raise TypeError(
            f'"{table}"."{column}" is a single-valued column in the SQL schema '
            "but multi-valued in the cimgraph data profile"
        )
    return value


def _upsert_statement(table: str, columns: tuple[str, ...]) -> str:
    column_list = ', '.join(f'"{c}"' for c in columns)
    placeholders = ', '.join(['%s'] * len(columns))
    updates = ', '.join(f'"{c}" = VALUES("{c}")' for c in columns)
    return (f'INSERT INTO "{table}" ({column_list}) VALUES ({placeholders}) '
            f'ON DUPLICATE KEY UPDATE {updates}')
