"""Tests for the MySQL connection and uploader.

The uploader targets relational schemas generated by UCAiug CIMTool; the
integration tests build the Tier Five Connectivity schema in a fresh
database for every test.

Prerequisites (integration tests only):
    - Docker daemon running
    - MySQL container: docker-compose up -d mysql

Usage:
    pytest tests/test_mysql.py -v
    pytest -m mysql
"""

import uuid

import pytest

from conftest import TIER_ONE_SQL_FILE, TEST_MODELS_DIR
from cimloader.databases.mysql import split_sql_script
from cimloader.uploaders.mysql import _sql_value


def _count(connection, table: str) -> int:
    return connection.execute(f'SELECT COUNT(*) FROM "{table}"')[0][0]


# =============================================================================
# Unit Tests (no database)
# =============================================================================

class TestSplitSqlScript:
    def test_drops_comments_and_separator_lines(self):
        script = (
            "-- comment\n"
            "------------------------------\n"
            'CREATE TABLE "A"\n(\n    -- column comment\n    "mRID" VARCHAR(100) PRIMARY KEY\n);\n'
            "INSERT INTO \"K\" ( \"name\" ) VALUES ( 'x' );\n"
        )
        assert split_sql_script(script) == [
            'CREATE TABLE "A"\n(\n    "mRID" VARCHAR(100) PRIMARY KEY\n)',
            "INSERT INTO \"K\" ( \"name\" ) VALUES ( 'x' )",
        ]

    def test_cimtool_schema_statements(self):
        statements = split_sql_script(TIER_ONE_SQL_FILE.read_text(encoding='utf-8'))
        assert all(s.startswith(('CREATE TABLE', 'ALTER TABLE', 'CREATE INDEX'))
                   for s in statements)
        assert sum(s.startswith('CREATE TABLE') for s in statements) == 21


class TestSqlValue:
    def test_conversions(self):
        import cimgraph.data_profile.rc4_2021 as cim

        base_voltage = cim.BaseVoltage(identifier=str(uuid.uuid4()))
        assert _sql_value(base_voltage, 'T', 'c') == base_voltage.uri()
        assert _sql_value(cim.PhaseCode.ABC, 'T', 'c') == 'ABC'
        assert _sql_value(True, 'T', 'c') == 1
        assert _sql_value(12.5, 'T', 'c') == 12.5

    def test_list_value_raises(self):
        with pytest.raises(TypeError, match='"T"."c"'):
            _sql_value([1, 2], 'T', 'c')


