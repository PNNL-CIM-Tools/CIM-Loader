@pytest.mark.integration
@pytest.mark.mysql
class TestMySQLSchema:
    def test_create_schema_populates_enumerations(self, mysql_uploader):
        names = {row[0] for row in mysql_uploader.execute('SELECT "name" FROM "PhaseCode"')}
        assert {'A', 'ABC', 's12N'} <= names

    def test_table_parents_follow_schema_inheritance(self, mysql_uploader):
        parents = mysql_uploader.table_parents()
        assert parents['Terminal'] == 'ACDCTerminal'
        assert parents['ACDCTerminal'] == 'IdentifiedObject'
        assert 'IdentifiedObject' not in parents

    def test_upload_without_schema_raises(self, mysql_uploader, tmp_path):
        empty_schema = tmp_path / 'empty.sql'
        empty_schema.write_text('-- no tables\n')
        mysql_uploader.drop_all()
        mysql_uploader.create_schema(str(empty_schema))
        with pytest.raises(RuntimeError, match='create_schema'):
            mysql_uploader.upload_from_graphmodel({})


@pytest.mark.integration
@pytest.mark.mysql
class TestMySQLUpload:
    def test_upload_from_file_ieee13(self, mysql_uploader):
        mysql_uploader.upload_from_file(str(TEST_MODELS_DIR), 'ieee13_2021.xml')

        assert _count(mysql_uploader, 'Terminal') == 69
        # Class-table inheritance: every Terminal also has its superclass rows.
        assert _count(mysql_uploader, 'ACDCTerminal') == 69
        rows = mysql_uploader.execute(
            'SELECT a."sequenceNumber", ce."name" FROM "Terminal" t '
            'JOIN "ACDCTerminal" a ON a."mRID" = t."mRID" '
            'JOIN "IdentifiedObject" ce ON ce."mRID" = t."ConductingEquipment" '
            'JOIN "ACLineSegment" line ON line."mRID" = t."ConductingEquipment"'
        )
        assert len(rows) == 22  # 11 lines x 2 terminals
        assert {sequence for sequence, _ in rows} == {1, 2}

    def test_upload_uses_schema_hierarchy_not_profile(self, mysql_uploader):
        # The Tier Five schema makes TransformerEnd a PowerSystemResource;
        # the rc4_2021 profile does not. Rows must follow the schema.
        mysql_uploader.upload_from_file(str(TEST_MODELS_DIR), 'ieee13_2021.xml')
        orphans = mysql_uploader.execute(
            'SELECT COUNT(*) FROM "TransformerEnd" e '
            'LEFT JOIN "PowerSystemResource" p ON p."mRID" = e."mRID" '
            'WHERE p."mRID" IS NULL'
        )
        assert _count(mysql_uploader, 'TransformerEnd') == 5
        assert orphans[0][0] == 0

    def test_reupload_is_idempotent(self, mysql_uploader):
        mysql_uploader.upload_from_file(str(TEST_MODELS_DIR), 'ieee13_2021.xml')
        first = _count(mysql_uploader, 'IdentifiedObject')
        mysql_uploader.upload_from_file(str(TEST_MODELS_DIR), 'ieee13_2021.xml')
        assert _count(mysql_uploader, 'IdentifiedObject') == first

    def test_upload_from_graphmodel(self, mysql_uploader):
        import cimgraph.data_profile.rc4_2021 as cim

        base_voltage = cim.BaseVoltage(
            identifier=str(uuid.uuid4()), name='BV_mysql', nominalVoltage=12470.0)
        line = cim.ACLineSegment(
            identifier=str(uuid.uuid4()), name='LINE_mysql',
            BaseVoltage=base_voltage, length=100.0)
        mysql_uploader.upload_from_graphmodel({
            cim.BaseVoltage: {base_voltage.identifier: base_voltage},
            cim.ACLineSegment: {line.identifier: line},
        })

        rows = mysql_uploader.execute(
            'SELECT bv."nominalVoltage", c."length" FROM "ConductingEquipment" ce '
            'JOIN "BaseVoltage" bv ON bv."mRID" = ce."BaseVoltage" '
            'JOIN "Conductor" c ON c."mRID" = ce."mRID" '
            'WHERE ce."mRID" = %s',
            (line.uri(),),
        )
        assert rows == [(12470.0, 100.0)]

    def test_upload_unsupported_format_raises(self, mysql_uploader):
        with pytest.raises(ValueError, match='RDF/XML and JSON-LD'):
            mysql_uploader.upload_from_file(str(TEST_MODELS_DIR), 'model.ttl')
